#!/usr/bin/env python3
"""
ORF results table dialog for the experimental guided UI shell.
"""

from __future__ import annotations

try:
    from PyQt6.QtCore import Qt
    from PyQt6.QtWidgets import (
        QDialog,
        QVBoxLayout,
        QLabel,
        QTableWidget,
        QTableWidgetItem,
        QHeaderView,
    )
    QT6 = True
except Exception:
    from PyQt5.QtCore import Qt
    from PyQt5.QtWidgets import (
        QDialog,
        QVBoxLayout,
        QLabel,
        QTableWidget,
        QTableWidgetItem,
        QHeaderView,
    )
    QT6 = False

from ppigfinder.ui_shell.branding import apply_ppigfinder_branding


def _window_flags():
    flags = Qt.WindowType.Window if QT6 else Qt.Window
    flags |= Qt.WindowType.WindowMinimizeButtonHint if QT6 else Qt.WindowMinimizeButtonHint
    flags |= Qt.WindowType.WindowMaximizeButtonHint if QT6 else Qt.WindowMaximizeButtonHint
    flags |= Qt.WindowType.WindowCloseButtonHint if QT6 else Qt.WindowCloseButtonHint
    return flags


class GuidedORFResultsDialog(QDialog):
    """
    Dialog showing lightweight guided ORF predictions.
    """

    def __init__(self, orfs, parent=None):
        super().__init__(parent)

        self.orfs = list(orfs or [])

        self.setWindowTitle("Guided ORF Table")
        self.setWindowFlags(_window_flags())
        self.resize(1100, 720)
        self.setMinimumSize(840, 560)
        self.setSizeGripEnabled(True)
        apply_ppigfinder_branding(self)

        layout = QVBoxLayout(self)
        layout.setContentsMargins(18, 18, 18, 18)
        layout.setSpacing(12)

        title = QLabel(
            f"Guided ORF predictions: {len(self.orfs)} ORFs"
        )
        title.setObjectName("SectionTitle")
        layout.addWidget(title)

        subtitle = QLabel(
            "This table is generated by the experimental guided six-frame ORF scanner. "
            "Full Pyrodigal/hybrid backend integration will be connected progressively."
        )
        subtitle.setWordWrap(True)
        layout.addWidget(subtitle)

        self.table = QTableWidget(0, 8, self)
        self.table.setHorizontalHeaderLabels(
            [
                "ORF ID",
                "Start",
                "End",
                "Strand",
                "Frame",
                "AA length",
                "Protein preview",
                "Nucleotide length",
            ]
        )

        header = self.table.horizontalHeader()
        try:
            mode = QHeaderView.ResizeMode.Stretch if QT6 else QHeaderView.Stretch
            header.setSectionResizeMode(mode)
        except Exception:
            pass

        self.table.setAlternatingRowColors(True)
        self._populate()
        layout.addWidget(self.table)

    def _populate(self) -> None:
        self.table.setRowCount(len(self.orfs))

        for row, orf in enumerate(self.orfs):
            protein = orf.protein_sequence or ""
            preview = protein[:40] + ("..." if len(protein) > 40 else "")

            values = [
                orf.id,
                str(orf.start),
                str(orf.end),
                orf.strand,
                str(orf.frame),
                str(orf.aa_length),
                preview,
                str(len(orf.nt_sequence)),
            ]

            for col, value in enumerate(values):
                item = QTableWidgetItem(value)
                self.table.setItem(row, col, item)


def show_guided_orf_results(orfs, parent=None) -> None:
    dialog = GuidedORFResultsDialog(orfs, parent=parent)
    dialog.showMaximized()
    dialog.exec() if hasattr(dialog, "exec") else dialog.exec_()
